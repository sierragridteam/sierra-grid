import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto('http://127.0.0.1:8184/?mode=demo');
await page.locator('#nodes .node').first().waitFor();
await page.waitForTimeout(800);
await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
await page.locator('#nodes').getByRole('button', { name: /Meadow/ }).click();
await page.locator('#compare').selectOption('4'.repeat(64));
await page.locator('#metric').selectOption('packets');
await page.locator('#findings').getByText(/1 reported reboot/).waitFor();
await page.screenshot({ path: 'artifacts/analysis.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: 'artifacts/narrow.png', fullPage: true });
await page.setViewportSize({ width: 1440, height: 1100 });
await page.goto('http://127.0.0.1:8184/?mode=demo&scenario=partial&node=' + '1'.repeat(64) + '&compare=' + '3'.repeat(64));
await page.locator('#coverage').getByText(/Unavailable/).waitFor();
await page.screenshot({ path: 'artifacts/partial.png', fullPage: true });
console.log({ pageErrors: errors });
await browser.close();
