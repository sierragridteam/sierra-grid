import { test, expect } from '@playwright/test';
const key = (n: number) => String(n).repeat(64);
test('node → comparison → metric → archive → return preserves filters and URL', async ({ page }) => {
    await page.goto('/?mode=demo');
    await page.getByRole('button', { name: 'Meadow Relay repeater' }).click();
    await expect(page.locator('#coverage')).toContainText('9 samples');
    await page.locator('#compare').selectOption(key(4));
    await page.locator('#metric').selectOption('packets');
    await expect(page.locator('#findings')).toContainText('1 reported reboot');
    await expect(page.locator('#findings')).toContainText('1 internal collection gap');
    await expect(page).toHaveURL(/compare=444/);
    await page.reload();
    await expect(page.locator('#metric')).toHaveValue('packets');
    await expect(page.locator('#compare')).toHaveValue(key(4));
    await page.getByRole('button', { name: 'Load bounded history' }).click();
    await expect(page.locator('#archive-status')).toContainText('End of returned pages');
    await expect(page.locator('#archive-table')).toContainText('tree obstructing');
    await page.getByRole('button', { name: 'Back to network' }).click();
    await expect(page.locator('#detail')).toBeHidden();
    await page.locator('#search').fill('Ridge');
    await expect(page.locator('#nodes .node')).toHaveCount(1);
    await page.locator('#nodes .node').click();
    await expect(page.locator('#node-facts')).toContainText('0%');
});
test('unknown, unmonitored, source stale, empty and unavailable stay distinct', async ({ page }) => {
    await page.goto('/?mode=demo&scenario=stale');
    await expect(page.locator('#health')).toContainText('STALE');
    await page.locator('#filter').selectOption('unknown');
    await expect(page.locator('#nodes .node')).toHaveCount(2);
    await page.locator('#nodes').getByRole('button', { name: /Valley/ }).click();
    await expect(page.locator('#node-facts')).toContainText('Not reported');
    await page.locator('#compare').selectOption(key(5));
    await expect(page.locator('#coverage')).toContainText('No samples returned');
    await page.goto('/?mode=demo&scenario=empty');
    await expect(page.locator('#nodes')).toContainText('No matching');
    await expect(page.locator('#links')).toContainText('No links returned');
    await page.goto('/?mode=demo&scenario=unavailable');
    await expect(page.locator('#nodes')).toContainText('Unavailable');
    await expect(page.locator('#links')).toContainText('Unavailable');
    await page.getByRole('button', { name: 'Refresh observations' }).click();
    await expect(page.locator('#nodes')).toContainText('Unavailable');
    await page.getByRole('button', { name: 'Load bounded history' }).click();
    await expect(page.locator('#archive-status')).toContainText('Unavailable');
});
test('partial short pages continue and independent telemetry failure is visible', async ({ page }) => {
    await page.goto('/?mode=demo&scenario=partial');
    await expect(page.locator('#nodes .node')).toHaveCount(6);
    await page.locator('#nodes').getByRole('button', { name: /Summit/ }).click();
    await page.locator('#compare').selectOption(key(3));
    await expect(page.locator('#coverage')).toContainText('Partial / truncated');
    await expect(page.locator('#coverage')).toContainText('Unavailable');
    await page.getByRole('button', { name: 'Load bounded history' }).click();
    await expect(page.locator('#archive-status')).toContainText('another page');
    let n = 0;
    while (await page.locator('#more-history').isVisible() && n++ < 20) {
        await page.locator('#more-history').click();
        await expect(page.locator('#more-history')).toBeEnabled();
    }
    await expect(page.locator('#archive-status')).toContainText('End of returned pages');
});
test('narrow layout and keyboard interaction', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/?mode=demo');
    await page.locator('#search').fill('Summit');
    await page.locator('#nodes .node').focus();
    await page.keyboard.press('Enter');
    await expect(page.locator('#node-title')).toHaveText('Summit Relay');
    await expect(page.locator('#coverage')).toContainText('Returned archive');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.locator('#history-chart summary').click();
    await expect(page.locator('#history-chart table')).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
test('endpoint comparison, changed bounds and back navigation restore investigation', async ({ page }) => {
    await page.goto('/?mode=demo&scenario=normal');
    await page.getByRole('button', { name: 'Compare endpoints' }).first().click();
    await expect(page.locator('#node-title')).toHaveText('Summit Relay');
    await expect(page.locator('#compare')).toHaveValue(key(2));
    await page.locator('#window').selectOption('72');
    await page.locator('#until').fill('2026-11-07T06:00');
    await page.getByRole('button', { name: 'Apply window' }).click();
    await expect(page.locator('#bounds')).toContainText('2026-11-04 06:00 UTC');
    await expect(page.locator('#coverage')).toContainText('Returned archive');
    await expect(page).toHaveURL(/hours=72/);
    await page.reload();
    await expect(page.locator('#until')).toHaveValue('2026-11-07T06:00');
    await expect(page.locator('#coverage')).toContainText('2026-11-07 05:00 UTC');
    await page.getByRole('button', { name: 'Back to network' }).click();
    await page.goBack();
    await expect(page.locator('#node-title')).toHaveText('Summit Relay');
    await expect(page.locator('#detail')).toBeVisible();
});
